package com.projectpilot.backend.controller;

import com.projectpilot.backend.dto.AiServiceDtos.AiGenerateRequest;
import com.projectpilot.backend.dto.AiServiceDtos.DocumentationResultDto;
import com.projectpilot.backend.entity.*;
import com.projectpilot.backend.exception.ResourceNotFoundException;
import com.projectpilot.backend.repository.*;
import com.projectpilot.backend.service.AiServiceClient;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;

import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

/**
 * Handles export of project artifacts (Markdown SRS, SQL, OpenAPI JSON).
 */
@RestController
@RequestMapping("/api/v1/projects/{projectId}/export")
public class ExportController {

    private final ProjectRepository projectRepository;
    private final ArchitectureRepository architectureRepository;
    private final DatabaseDesignRepository databaseDesignRepository;
    private final ApiDefinitionRepository apiDefinitionRepository;
    private final SprintRepository sprintRepository;
    private final CostEstimateRepository costEstimateRepository;
    private final RiskRepository riskRepository;
    private final AiServiceClient aiServiceClient;

    public ExportController(ProjectRepository projectRepository,
                             ArchitectureRepository architectureRepository,
                             DatabaseDesignRepository databaseDesignRepository,
                             ApiDefinitionRepository apiDefinitionRepository,
                             SprintRepository sprintRepository,
                             CostEstimateRepository costEstimateRepository,
                             RiskRepository riskRepository,
                             AiServiceClient aiServiceClient) {
        this.projectRepository = projectRepository;
        this.architectureRepository = architectureRepository;
        this.databaseDesignRepository = databaseDesignRepository;
        this.apiDefinitionRepository = apiDefinitionRepository;
        this.sprintRepository = sprintRepository;
        this.costEstimateRepository = costEstimateRepository;
        this.riskRepository = riskRepository;
        this.aiServiceClient = aiServiceClient;
    }

    @GetMapping("/markdown")
    @PreAuthorize("isAuthenticated()")
    public ResponseEntity<byte[]> exportMarkdown(@PathVariable UUID projectId) {
        Project project = getProject(projectId);
        String markdown = buildMarkdown(project);

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.TEXT_PLAIN);
        headers.set(HttpHeaders.CONTENT_DISPOSITION,
                "attachment; filename=\"" + sanitizeFilename(project.getTitle()) + "_blueprint.md\"");

        return ResponseEntity.ok().headers(headers).body(markdown.getBytes(StandardCharsets.UTF_8));
    }

    @GetMapping("/sql")
    @PreAuthorize("isAuthenticated()")
    public ResponseEntity<byte[]> exportSql(@PathVariable UUID projectId) {
        Project project = getProject(projectId);
        String sql = databaseDesignRepository.findFirstByProjectIdOrderByCreatedAtDesc(projectId)
                .map(DatabaseDesign::getMigrationSql)
                .orElse("-- No database design generated yet. Run /generate/database first.\n");

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.TEXT_PLAIN);
        headers.set(HttpHeaders.CONTENT_DISPOSITION,
                "attachment; filename=\"" + sanitizeFilename(project.getTitle()) + "_schema.sql\"");

        return ResponseEntity.ok().headers(headers).body(sql.getBytes(StandardCharsets.UTF_8));
    }

    @GetMapping("/openapi")
    @PreAuthorize("isAuthenticated()")
    public ResponseEntity<byte[]> exportOpenApi(@PathVariable UUID projectId) {
        Project project = getProject(projectId);
        List<ApiDefinition> endpoints = apiDefinitionRepository.findByProjectId(projectId);

        StringBuilder spec = new StringBuilder();
        spec.append("{\n");
        spec.append("  \"openapi\": \"3.0.3\",\n");
        spec.append("  \"info\": {\n");
        spec.append("    \"title\": \"").append(project.getTitle()).append(" API\",\n");
        spec.append("    \"description\": \"Generated by ProjectPilot AI\",\n");
        spec.append("    \"version\": \"1.0.0\"\n");
        spec.append("  },\n");
        spec.append("  \"servers\": [{\"url\": \"/api/v1\", \"description\": \"API Base\"}],\n");
        spec.append("  \"paths\": {\n");
        for (int i = 0; i < endpoints.size(); i++) {
            ApiDefinition ep = endpoints.get(i);
            spec.append("    \"").append(ep.getEndpointPath()).append("\": {\n");
            spec.append("      \"").append(ep.getHttpMethod().toLowerCase()).append("\": {\n");
            spec.append("        \"summary\": \"").append(escapeJson(ep.getSummary())).append("\",\n");
            spec.append("        \"security\": ").append(Boolean.TRUE.equals(ep.getAuthRequired()) ? "[{\"bearerAuth\": []}]" : "[]").append(",\n");
            spec.append("        \"responses\": {\"200\": {\"description\": \"Success\"}}\n");
            spec.append("      }\n");
            spec.append("    }").append(i < endpoints.size() - 1 ? "," : "").append("\n");
        }
        spec.append("  },\n");
        spec.append("  \"components\": {\n");
        spec.append("    \"securitySchemes\": {\n");
        spec.append("      \"bearerAuth\": {\"type\": \"http\", \"scheme\": \"bearer\", \"bearerFormat\": \"JWT\"}\n");
        spec.append("    }\n");
        spec.append("  }\n");
        spec.append("}\n");

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        headers.set(HttpHeaders.CONTENT_DISPOSITION,
                "attachment; filename=\"" + sanitizeFilename(project.getTitle()) + "_openapi.json\"");

        return ResponseEntity.ok().headers(headers).body(spec.toString().getBytes(StandardCharsets.UTF_8));
    }

    private Project getProject(UUID projectId) {
        return projectRepository.findById(projectId)
                .orElseThrow(() -> new ResourceNotFoundException("Project not found: " + projectId));
    }

    private String buildMarkdown(Project project) {
        StringBuilder md = new StringBuilder();
        md.append("# ").append(project.getTitle()).append(" — Blueprint\n\n");
        md.append("**Generated by ProjectPilot AI** | Status: ").append(project.getStatus()).append("\n\n");
        md.append("---\n\n");

        // Description
        if (project.getDescription() != null) {
            md.append("## Project Description\n\n").append(project.getDescription()).append("\n\n");
        }

        // Architecture
        architectureRepository.findFirstByProjectIdOrderByCreatedAtDesc(project.getId()).ifPresent(arch -> {
            md.append("## System Architecture\n\n");
            md.append("**Style:** ").append(arch.getStyle()).append("\n\n");
            md.append(arch.getSummary()).append("\n\n");
            if (arch.getMermaidDiagram() != null) {
                md.append("```mermaid\n").append(arch.getMermaidDiagram()).append("\n```\n\n");
            }
            if (arch.getDeploymentStrategy() != null) {
                md.append("**Deployment:** ").append(arch.getDeploymentStrategy()).append("\n\n");
            }
        });

        // Database
        databaseDesignRepository.findFirstByProjectIdOrderByCreatedAtDesc(project.getId()).ifPresent(db -> {
            md.append("## Database Design\n\n");
            if (db.getMermaidErDiagram() != null) {
                md.append("```mermaid\n").append(db.getMermaidErDiagram()).append("\n```\n\n");
            }
        });

        // API Endpoints
        List<ApiDefinition> endpoints = apiDefinitionRepository.findByProjectId(project.getId());
        if (!endpoints.isEmpty()) {
            md.append("## API Endpoints\n\n");
            md.append("| Method | Path | Summary | Auth |\n|---|---|---|---|\n");
            endpoints.forEach(ep -> md.append("| ").append(ep.getHttpMethod()).append(" | ")
                    .append(ep.getEndpointPath()).append(" | ").append(ep.getSummary() != null ? ep.getSummary() : "").append(" | ")
                    .append(Boolean.TRUE.equals(ep.getAuthRequired()) ? "JWT" : "None").append(" |\n"));
            md.append("\n");
        }

        // Sprints
        List<Sprint> sprints = sprintRepository.findByProjectIdOrderBySprintNumberAsc(project.getId());
        if (!sprints.isEmpty()) {
            md.append("## Sprint Plan\n\n");
            sprints.forEach(sprint -> {
                md.append("### ").append(sprint.getName()).append("\n\n");
                md.append("**Goal:** ").append(sprint.getGoal() != null ? sprint.getGoal() : "").append("\n\n");
            });
        }

        // Cost
        costEstimateRepository.findFirstByProjectIdOrderByCreatedAtDesc(project.getId()).ifPresent(cost -> {
            md.append("## Cost Estimate\n\n");
            md.append("**Total Monthly:** $").append(cost.getTotalMonthlyUsd()).append("\n\n");
            if (cost.getBreakdownNotes() != null) md.append(cost.getBreakdownNotes()).append("\n\n");
        });

        // Risks
        List<Risk> risks = riskRepository.findByProjectId(project.getId());
        if (!risks.isEmpty()) {
            md.append("## Risk Analysis\n\n");
            md.append("| Category | Description | Probability | Impact | Severity |\n|---|---|---|---|---|\n");
            risks.forEach(r -> md.append("| ").append(r.getCategory()).append(" | ")
                    .append(r.getDescription(), 0, Math.min(60, r.getDescription().length())).append("... | ")
                    .append(r.getProbability()).append(" | ").append(r.getImpact()).append(" | ")
                    .append(r.getSeverityScore()).append(" |\n"));
        }

        md.append("\n---\n*Exported from ProjectPilot AI*\n");
        return md.toString();
    }

    private String sanitizeFilename(String name) {
        return name != null ? name.replaceAll("[^a-zA-Z0-9_-]", "_").toLowerCase() : "project";
    }

    private String escapeJson(String value) {
        if (value == null) return "";
        return value.replace("\"", "\\\"").replace("\n", "\\n");
    }
}

