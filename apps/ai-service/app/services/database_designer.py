def generate_database_design(project_title: str, project_description: str, requirements_context: str = "") -> DatabaseDesignResult:
    if settings.GEMINI_API_KEY and len(settings.GEMINI_API_KEY) > 5 and not settings.GEMINI_API_KEY.startswith("your_"):
        try:
            genai.configure(api_key=settings.GEMINI_API_KEY)
            model = genai.GenerativeModel("gemini-1.5-flash", system_instruction=SYSTEM_PROMPT_DATABASE)
            prompt = f"Project: {project_title}\nDescription: {project_description}\nContext: {requirements_context}"
            response = model.generate_content(prompt)
            data = json.loads(_extract_json(response.text))
            return DatabaseDesignResult.model_validate(data)
        except Exception as e:
            logger.warning(f"DatabaseDesigner: Gemini call failed ({e}). Using deterministic fallback.")

    return _generate_fallback_database(project_title, project_description)

