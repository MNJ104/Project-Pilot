def generate_documentation(project_title: str, project_description: str, requirements_context: str = "") -> DocumentationResult:
    if settings.GEMINI_API_KEY and len(settings.GEMINI_API_KEY) > 5 and not settings.GEMINI_API_KEY.startswith("your_"):
        try:
            genai.configure(api_key=settings.GEMINI_API_KEY)
            model = genai.GenerativeModel("gemini-1.5-flash", system_instruction=SYSTEM_PROMPT_DOCS)
            prompt = (
                f"Project Title: {project_title}\n"
                f"Description: {project_description}\n"
                f"Context: {requirements_context}\n\n"
                "Generate a complete IEEE 830 SRS document in Markdown format. "
                "Return ONLY the raw markdown text, no JSON wrapper."
            )
            response = model.generate_content(prompt)
            srs_text = response.text.strip()
            return DocumentationResult(
                project_title=project_title,
                srs_markdown=srs_text,
                executive_summary=f"AI-generated SRS for {project_title}. See full document for details.",
                tech_stack_summary="See Technology Stack section in the SRS document."
            )
        except Exception as e:
            logger.warning(f"DocumentationGenerator: Gemini call failed ({e}). Using deterministic fallback.")

    return _generate_fallback_documentation(project_title, project_description)

